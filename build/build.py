#!/usr/bin/env python3
"""Build step for the leadership microsite.
Reads build/roles.json and build/site.json, then writes:
  roles.js, index.html (meta), roles/<id>/index.html, og/*.png, sitemap.xml, robots.txt, apps-script/Thanks.gs
Run from anywhere:  python3 build/build.py
"""
import json, re, os, html
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)
roles = json.load(open(P('build', 'roles.json'), encoding='utf-8'))
site = json.load(open(P('build', 'site.json')))
BASE = site['siteUrl'].rstrip('/') + '/'
money = lambda s: s.replace('Rs ', '₹')
E = lambda s: html.escape(s, quote=True)

# ---------- roles.js ----------
with open(P('roles.js'), 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by build/build.py from build/roles.json. Edit that file, then run the build. */\n')
    f.write('window.SITE_URL = %s;\n' % json.dumps(BASE))
    f.write('window.SLA = {ack: %d, outcome: %d};\n' % (site['slaAckDays'], site['slaOutcomeDays']))
    f.write('window.ROLES = %s;\n' % json.dumps(roles, indent=1, ensure_ascii=False))

# ---------- OG images ----------
W, H = 1200, 630
RED, INK, WHITE = (232, 37, 42), (17, 17, 17), (255, 255, 255)
F = lambda w, s: ImageFont.truetype(P('fonts', 'Poppins-%s.ttf' % w), s)
logo = Image.open(P('assets', 'logo-wide.png')).convert('RGBA')
photos = {'home': 'pb-team-outdoor.webp', 'president-gsm': 'pb-global-walk.webp', 'president-enterprise': 'pb-leaders-group.webp', 'ctpo': 'pb-technology.webp', 'csto': 'pb-executive.webp', 'president-grad': 'pb-team-table.webp', 'president-eduverse': 'pb-partnerships.webp', 'director-b2c': 'pb-conversation.webp', 'president-campusos': 'pb-team-circle.webp', 'director-gsm-sa-gmo': 'pb-mentor.webp', 'director-gsm-sea-gmo': 'pb-working-pair.webp', 'director-gsm-sea-marketplace': 'pb-team-table.webp'}

def wrap(draw, text, font, maxw):
    lines, cur = [], ''
    for w in text.split():
        t = (cur + ' ' + w).strip()
        if draw.textlength(t, font=font) <= maxw: cur = t
        else: lines.append(cur); cur = w
    lines.append(cur); return lines

def cover(img, w, h):
    r = max(w / img.width, h / img.height)
    img = img.resize((int(img.width * r) + 1, int(img.height * r) + 1), Image.LANCZOS)
    x, y = (img.width - w) // 2, (img.height - h) // 2
    return img.crop((x, y, x + w, y + h))

def og(name, kicker, title, photo, size=64):
    im = Image.new('RGB', (W, H), RED); d = ImageDraw.Draw(im)
    # photo tile with identity-shape corners (upper right and lower left)
    tx, ty, tw, th = 730, 60, 410, 510
    tile = cover(Image.open(P('assets', photo)).convert('RGB'), tw, th)
    mask = Image.new('L', (tw, th), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, tw - 1, th - 1), radius=70, fill=255, corners=(False, True, False, True))
    # ink offset block behind the photo
    d.rounded_rectangle((tx - 22, ty + 26, tx + tw - 22, ty + th + 26), radius=70, fill=INK, corners=(False, True, False, True))
    im.paste(tile, (tx, ty), mask)
    # text
    d.text((64, 70), kicker.upper(), font=F('SemiBold', 24), fill=(255, 255, 255))
    f = F('ExtraBold', size)
    lines = wrap(d, title, f, 600)
    while len(lines) > 4 and size > 40:
        size -= 4; f = F('ExtraBold', size); lines = wrap(d, title, f, 600)
    y = 130
    for ln in lines:
        d.text((64, y), ln, font=f, fill=WHITE); y += int(size * 1.12)
    # logo plate
    lw = 210; lg = logo.resize((lw, int(logo.height * lw / logo.width)), Image.LANCZOS)
    pw, ph = lw + 44, lg.height + 36
    px, py = 64, H - 64 - ph
    d.rounded_rectangle((px, py, px + pw, py + ph), radius=22, fill=WHITE, corners=(False, True, False, True))
    im.paste(lg, (px + 22, py + 18), lg)
    d.text((px + pw + 24, py + ph // 2 - 15), 'msmunify.com', font=F('Medium', 26), fill=WHITE)
    os.makedirs(P('og'), exist_ok=True)
    im.save(P('og', name + '.png'), optimize=True)

og('home', 'MSM Unify leadership careers', 'Lead the team that reaches 5 million learners.', photos['home'], 62)
for i, r in enumerate(roles):
    og(r['id'], 'Open leadership seat', r['title'], photos[r['id']], 66)


# ---------- Gallery block (static HTML, written into index.html before role pages are made) ----------
G0, G1 = '<!--GALLERY-->', '<!--/GALLERY-->'
gal = json.load(open(P('build', 'gallery.json'), encoding='utf-8'))
def tile(it, hidden=False):
    return '<figure class="reel-tile"%s><img src="%s" alt="%s" width="%d" height="%d" loading="lazy" decoding="async"%s></figure>' % (' aria-hidden="true"' if hidden else '', it['src'], '' if hidden else E(it['alt']), it['w'], it['h'], '')
rows_html = ''
for i, row in enumerate(gal):
    d = 'a' if i % 2 == 0 else 'b'
    rows_html += '      <div class="reel reel-%s"><div class="reel-track"><div class="reel-set">%s</div><div class="reel-set" aria-hidden="true">%s</div></div></div>\n' % (d, ''.join(tile(x) for x in row), ''.join(tile(x, True) for x in row))
_t = open(P('index.html'), encoding='utf-8').read()
_a, _b = _t.index(G0) + len(G0), _t.index(G1)
open(P('index.html'), 'w', encoding='utf-8').write(_t[:_a] + '\n' + rows_html + '      ' + _t[_b:])

# ---------- HTML ----------
tpl = open(P('index.html'), encoding='utf-8').read()

# ---------- Versioned asset paths ----------
# CDNs and browsers keep scripts and stylesheets for up to 30 days. Each build copies the four site files into
# v/<hash>/ and points every page at that folder, so a new deploy always gets new URLs and nothing stale is served.
# A path (and not a ?v= query string) is used because many CDNs ignore query strings when caching.
import hashlib, shutil
tpl = re.sub(r'v/[0-9a-f]{10}/(styles\.css|config\.js|roles\.js|app\.js)', r'\1', tpl)   # undo a previous build's rewrite
ASSET_FILES = ('styles.css', 'config.js', 'roles.js', 'app.js')
_h = hashlib.sha1()
for _f in ASSET_FILES:
    _h.update(open(P(_f), 'rb').read())
VER = _h.hexdigest()[:10]
os.makedirs(P('v', VER), exist_ok=True)
for _f in ASSET_FILES:
    shutil.copy(P(_f), P('v', VER, _f))
open(P('v', '.gitignore'), 'w').write('*\n')   # v/ is generated, so it keeps itself out of git

def version(s):
    return re.sub(r'((?:href|src)=")((?:\.\./\.\./)?)(styles\.css|config\.js|roles\.js|app\.js)"',
                  lambda m: '%s%sv/%s/%s"' % (m.group(1), m.group(2), VER, m.group(3)), s)

M0, M1 = '<!--META-->', '<!--/META-->'
a, b = tpl.index(M0), tpl.index(M1)

def meta(title, desc, url, image):
    t, d = E(money(title)), E(money(desc))
    return (M0 + '\n<title>%s</title>\n<meta name="description" content="%s">\n<link rel="canonical" href="%s">\n'
      '<meta property="og:type" content="website">\n<meta property="og:site_name" content="MSM Unify">\n'
      '<meta property="og:title" content="%s">\n<meta property="og:description" content="%s">\n<meta property="og:url" content="%s">\n'
      '<meta property="og:image" content="%s">\n<meta property="og:image:width" content="1200">\n<meta property="og:image:height" content="630">\n'
      '<meta property="og:image:alt" content="%s">\n'
      '<meta name="twitter:card" content="summary_large_image">\n<meta name="twitter:title" content="%s">\n'
      '<meta name="twitter:description" content="%s">\n<meta name="twitter:image" content="%s">\n') % (t, d, url, t, d, url, image, t, t, d, image)

home_meta = meta('Leadership Careers | MSM Unify', 'Eleven leadership seats are open at MSM Unify. Read the story behind each role and apply.', BASE, BASE + 'og/home.png')
home_meta = home_meta.replace('<meta property="og:title" content="Leadership Careers | MSM Unify">', '<meta property="og:title" content="Lead the team that reaches 5 million learners | MSM Unify">').replace('<meta name="twitter:title" content="Leadership Careers | MSM Unify">', '<meta name="twitter:title" content="Lead the team that reaches 5 million learners | MSM Unify">')
home = version(tpl[:a] + home_meta + tpl[b:])
open(P('index.html'), 'w', encoding='utf-8').write(home)

def prefix(s):
    return re.sub(r'(href|src)="(assets/|styles\.css|config\.js|roles\.js|app\.js)', r'\1="../../\2', s)

for r in roles:
    url = BASE + 'roles/%s/' % r['id']
    page = tpl[:a] + meta(r['share']['title'] + ' | MSM Unify', r['share']['desc'], url, BASE + 'og/%s.png' % r['id']).replace('og:image:alt" content="', 'og:image:alt" content="') + tpl[b:]
    page = page.replace('<script src="config.js">', '<script>window.OPEN_ROLE=%s;</script>\n<script src="config.js">' % json.dumps(r['id']), 1)
    page = version(prefix(page))
    os.makedirs(P('roles', r['id']), exist_ok=True)
    open(P('roles', r['id'], 'index.html'), 'w', encoding='utf-8').write(page)

# ---------- sitemap, robots ----------
urls = [BASE] + [BASE + 'roles/%s/' % r['id'] for r in roles]
open(P('sitemap.xml'), 'w').write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join('  <url><loc>%s</loc></url>\n' % u for u in urls) + '</urlset>\n')
open(P('robots.txt'), 'w').write('User-agent: *\nAllow: /\nSitemap: %ssitemap.xml\n' % BASE)

# ---------- Apps Script role table ----------
def y1(r):
    if r.get('milestones'): return money(r['milestones'][-1]['text'])
    if r.get('measures'): return money('; '.join(r['measures'][:2]) + '.')
    return money(r.get('why', ''))
table = {r['title']: {'lead': money(r['thanks']['lead']), 'ready': money(r['thanks']['ready']), 'hook': money(r['hook']),
                      'url': BASE + 'roles/%s/' % r['id'], 'owns': [money(x) for x in r.get('owns', [])[:3]], 'y1': y1(r)} for r in roles}
table['Best fit, you decide'] = {'lead': 'You asked us to match you to the best-fit seat, so your application will be read against every open leadership role, not just one.', 'ready': 'Come ready to tell us where you would add the most value in your first year, and how you would measure it.',
                                 'hook': 'Open to the best fit', 'url': BASE, 'owns': [], 'y1': 'Every seat has a written mandate: what you own, what success looks like in 12 months, and how you are measured. You will see the one that fits you in writing before the final stage.'}
with open(P('apps-script', 'Thanks.gs'), 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by build/build.py. Per-role thank-you copy. Edit build/roles.json, then rebuild. */\n')
    f.write('var HR_EMAIL = %s;\n' % json.dumps(site['hrEmail']))
    f.write('var SITE_URL = %s;\n' % json.dumps(BASE))
    f.write('var SLA_ACK_DAYS = %d;\nvar SLA_OUTCOME_DAYS = %d;\n' % (site['slaAckDays'], site['slaOutcomeDays']))
    f.write('var THANKS = %s;\n' % json.dumps(table, indent=1, ensure_ascii=False))
open(P('apps-script', 'MSM-Leadership-Applications.gs'), 'w', encoding='utf-8').write(open(P('apps-script', 'Code.gs'), encoding='utf-8').read() + '\n\n' + open(P('apps-script', 'Thanks.gs'), encoding='utf-8').read())
print('built', len(roles), 'roles,', len(urls), 'urls')
